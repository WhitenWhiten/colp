import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { domainToASCII } from 'node:url';
import { fileURLToPath } from 'node:url';

/* The Public Suffix List, as the extension reads it (src/automation/public-suffix.ts):
   every rule of the ICANN and PRIVATE sections of the copy vendored under
   third_party/public-suffix-list at the commit its VERSION names, each label in
   ASCII (punycode), sorted, one per line. A rule is plain ("co.uk"), a wildcard
   ("*.ck") or an exception ("!www.ck"). Update the list by replacing the vendored
   file and VERSION, then run this script without --check. */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const vendored = resolve(root, 'third_party/public-suffix-list');
const output = resolve(root, 'src/generated/public-suffix-list.ts');

const version = await readFile(resolve(vendored, 'VERSION'), 'utf8');
const commit = /^commit: ([0-9a-f]{40})$/mu.exec(version)?.[1];
assert.ok(commit, 'third_party/public-suffix-list/VERSION names no commit');
const text = await readFile(resolve(vendored, 'public_suffix_list.dat'), 'utf8');
assert.ok(text.includes('===BEGIN ICANN DOMAINS===') && text.includes('===BEGIN PRIVATE DOMAINS==='), 'not a Public Suffix List');

function ascii(rule) {
  const prefix = rule.startsWith('!') ? '!' : rule.startsWith('*.') ? '*.' : '';
  const name = domainToASCII(rule.slice(prefix.length));
  assert.ok(name && !name.includes('*'), `rule cannot be read: ${rule}`);
  return prefix + name;
}
// A rule is the first whitespace-free token of a line that is not a comment.
const rules = [...new Set(text.split('\n').map((line) => line.trim().split(/\s/u)[0]).filter((line) => line && !line.startsWith('//')).map(ascii))]
  .sort();

const generated = `// Generated by scripts/generate-public-suffix.mjs from third_party/public-suffix-list; do not edit.
// The Public Suffix List (https://publicsuffix.org) is subject to the Mozilla Public License 2.0:
// https://mozilla.org/MPL/2.0/. Source: https://github.com/publicsuffix/list/blob/${commit}/public_suffix_list.dat
export const PUBLIC_SUFFIX_COMMIT = '${commit}';
/** ICANN and PRIVATE rules, ASCII, sorted, one per line: plain, \`*.\` wildcard or \`!\` exception. */
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify(rules.join('\n'))};
`;
if (process.argv.includes('--check')) {
  assert.equal(await readFile(output, 'utf8').catch(() => ''), generated,
    'src/generated/public-suffix-list.ts does not match third_party/public-suffix-list');
} else {
  await writeFile(output, generated);
}
