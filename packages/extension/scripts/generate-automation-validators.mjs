import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/* The @know-n/colp automation core validates with Ajv, which compiles each
   schema into a Function at runtime. MV3 forbids that (no 'unsafe-eval'), so
   the extension build swaps the core's Ajv for these standalone validators
   (scripts/automation-ajv-plugin.mjs). They are generated from the exact
   schema objects the installed core compiles, with the same Ajv options. */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const coreRequire = createRequire(resolve(root, 'node_modules/@know-n/colp/dist/automation/index.js'));
const { Ajv2020 } = coreRequire('ajv/dist/2020.js');
const standaloneCode = coreRequire('ajv/dist/standalone/index.js').default;
const addFormats = coreRequire('ajv-formats');

/** Every schema the core compiles internally, plus the device and Product DTOs the extension reads or sends. */
export const AUTOMATION_VALIDATORS = ['EventFacts', 'Predicate', 'RuleDefinition', 'RuleBundle', 'BundleAckInput',
  'OperationReceipt', 'LocalReceiptInput', 'ReceiptIngestResult', 'Run', 'RunPage', 'RulePage', 'PauseState'];

const captured = new Map();
const compile = Object.getPrototypeOf(Ajv2020.prototype).compile;
Object.getPrototypeOf(Ajv2020.prototype).compile = function capture(schema, meta) {
  if (schema && typeof schema.$ref === 'string') captured.set(schema.$ref, { schema, options: this.opts });
  return compile.call(this, schema, meta);
};
const core = await import(pathToFileURL(resolve(root, 'node_modules/@know-n/colp/dist/automation/index.js')).href);
for (const name of AUTOMATION_VALIDATORS) core.prepareAutomationSchema(name);
Object.getPrototypeOf(Ajv2020.prototype).compile = compile;

const first = captured.get(`#/$defs/${AUTOMATION_VALIDATORS[0]}`);
assert.ok(first, 'the automation core did not compile through the shared Ajv');
const { $schema, $defs } = first.schema;
for (const name of AUTOMATION_VALIDATORS) {
  const entry = captured.get(`#/$defs/${name}`);
  assert.ok(entry, `the automation core did not compile ${name}`);
  assert.equal(entry.schema.$defs, $defs, `${name} uses another definition set`);
  assert.deepEqual(Object.keys(entry.schema).sort(), ['$defs', '$ref', '$schema'], `${name} root shape changed`);
}
const options = { strict: first.options.strict, allErrors: first.options.allErrors,
  validateFormats: first.options.validateFormats, discriminator: first.options.discriminator };
assert.deepEqual(options, { strict: false, allErrors: false, validateFormats: true, discriminator: true },
  'the automation core changed its Ajv options; review the standalone generation');

const base = 'https://known.example/extension/generated/automation';
const ajv = new Ajv2020({ ...options, code: { source: true, esm: true, optimize: true } });
addFormats(ajv);
ajv.addSchema({ $id: base, $schema, $defs }, base);
const exports = Object.fromEntries(AUTOMATION_VALIDATORS.map((name) => {
  const id = `${base}/${name}`;
  ajv.addSchema({ $id: id, $ref: `${base}#/$defs/${name}` }, id);
  return [name, id];
}));
// ajv-formats exposes `uri` as a function, while Ajv's standalone reference treats every
// overridden format as a definition object. Same normalization as the protocol validators.
let code = standaloneCode(ajv, exports);
for (const [, index] of code.matchAll(/const formats(\d+) = require\("ajv-formats\/dist\/formats"\)\.fullFormats\.uri;/gu)) {
  code = code.replaceAll(`formats${index}.validate(`, `formats${index}(`);
}
const generated = `${code}\n`;
const declarations = `/* Generated by scripts/generate-automation-validators.mjs. */
export interface StandaloneValidator { (data: unknown): boolean; errors?: Array<{ instancePath: string; keyword: string; message?: string }> | null }
${AUTOMATION_VALIDATORS.map((name) => `export declare const ${name}: StandaloneValidator;`).join('\n')}
`;
const output = resolve(root, 'src/generated/automation-validators.js');
const declarationOutput = resolve(root, 'src/generated/automation-validators.d.ts');
if (process.argv.includes('--check')) {
  assert.equal(await readFile(output, 'utf8').catch(() => ''), generated,
    'automation validators do not match the installed @know-n/colp automation schema');
  assert.equal(await readFile(declarationOutput, 'utf8').catch(() => ''), declarations,
    'automation validator declarations are out of date');
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, generated);
  await writeFile(declarationOutput, declarations);
}
