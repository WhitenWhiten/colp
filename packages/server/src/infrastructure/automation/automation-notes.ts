import { sql } from 'kysely';
import type { DatabaseTransaction } from '../database/unit-of-work.js';

/**
 * Text outputs never edit a note the Owner wrote. Each lands in its own plain private note whose
 * creator identifies the rule, so the Owner's note stays the Owner's (and stays the worker `note`
 * input), and the Owner can delete the automation note without losing their own text.
 */
const AUTOMATION_CREATOR_PREFIX = 'urn:colp:automation:rule:';
const MODEL_LABEL_MAX = 64;

export function automationNoteCreator(ruleId: string): { id: string; name: string } {
  return { id: AUTOMATION_CREATOR_PREFIX + ruleId, name: 'Automation' };
}

/** Worker-supplied labels are untrusted: one line, no control characters, bounded. */
export function sanitizeModelLabel(label: string | undefined): string | undefined {
  const clean = label?.replace(/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]+/gu, ' ').replace(/\s+/gu, ' ').trim().slice(0, MODEL_LABEL_MAX).trim();
  return clean || undefined;
}

export function attributedNoteText(text: string, modelLabel: string | undefined): string {
  const label = sanitizeModelLabel(modelLabel);
  return `${text}\n\n— Generated by automation${label ? ` (${label})` : ''}`;
}

/** An earlier, still-present note from the same rule on this bookmark: review instead of stacking notes. */
export async function hasLiveAutomationNote(tx: DatabaseTransaction, collectionId: string, nodeId: string, ruleId: string): Promise<boolean> {
  const row = await tx.selectFrom('annotations').select('id')
    .where('collection_id', '=', collectionId).where('subject_type', '=', 'node').where('subject_id', '=', nodeId)
    .where('deleted_at', 'is', null).where(sql<string>`payload_json->'creator'->>'id'`, '=', automationNoteCreator(ruleId).id)
    .limit(1).executeTakeFirst();
  return row !== undefined;
}

/** SQL predicate excluding automation-authored notes from the Owner's note set. */
export const ownerAuthoredNote = sql<boolean>`coalesce(payload_json->'creator'->>'id','') NOT LIKE ${AUTOMATION_CREATOR_PREFIX + '%'}`;
