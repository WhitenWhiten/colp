/** Export only committed COLP/protocol/tooling files, without the parent project's history. */
import { execFile } from 'node:child_process';
import { access, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { standaloneRoots, assertExportEntry, filterStandaloneAllowlist } from './lib/standalone-layout.mjs';
const exec = promisify(execFile);
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(packageRoot, '..', '..');

async function assertRelativeModuleClosure(root, files) {
  const ts = await import('typescript');
  const names = new Set(files);
  const unresolved = [];
  for (const file of files) {
    if (!/\.(?:[cm]?js|[cm]?ts|tsx)$/u.test(file)) continue;
    const source = await readFile(resolve(root, file), 'utf8');
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    const specifiers = [];
    const visit = node => {
      if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node))
        && node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier)) specifiers.push(node.moduleSpecifier.text);
      if (ts.isCallExpression(node) && node.arguments.length === 1
        && (node.expression.kind === ts.SyntaxKind.ImportKeyword
          || (ts.isIdentifier(node.expression) && node.expression.text === 'require'))
        && ts.isStringLiteral(node.arguments[0])) specifiers.push(node.arguments[0].text);
      ts.forEachChild(node, visit);
    };
    visit(ast);
    for (const specifier of specifiers) {
      if (!specifier.startsWith('.')) continue;
      const target = relative(root, resolve(root, dirname(file), specifier)).split(sep).join('/');
      if (target.startsWith('../')) { unresolved.push(file + ' -> ' + specifier); continue; }
      // dist is intentionally generated by the exported package's own build.
      if (target.startsWith('packages/node/dist/')) continue;
      const variants = [target, target.replace(/\.js$/u, '.ts'), target.replace(/\.mjs$/u, '.mts'),
        target.replace(/\.cjs$/u, '.cts'), target + '.ts', target + '.js', target + '/index.ts', target + '/index.js'];
      if (!variants.some(candidate => names.has(candidate))) unresolved.push(file + ' -> ' + specifier);
    }
  }
  if (unresolved.length > 0) throw new Error('Standalone module boundary is incomplete:\n' + unresolved.join('\n'));
}

export async function exportStandalone(destination) {
  destination = resolve(destination);
  const comparison = process.platform === 'win32' ? destination.toLowerCase() : destination;
  const sourceComparison = process.platform === 'win32' ? repositoryRoot.toLowerCase() : repositoryRoot;
  if (comparison === sourceComparison || comparison.startsWith(sourceComparison + sep)) {
    throw new Error('Choose a destination outside the current repository.');
  }
  try { await access(destination); throw new Error('The destination already exists.'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const git = async args => (await exec('git', args, { cwd: repositoryRoot,
    encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 })).stdout;
  if ((await git(['status', '--porcelain'])).length !== 0) throw new Error('Export requires a clean committed checkout.');
  const sourceRevision = (await git(['rev-parse', 'HEAD'])).trim();
  const entries = (await git(['ls-tree', '-r', '-z', '--full-tree', sourceRevision, '--', ...standaloneRoots]))
    .split('\0').filter(Boolean).map(entry => {
      const tab = entry.indexOf('\t');
      const [mode, type] = entry.slice(0, tab).split(' ');
      const path = entry.slice(tab + 1);
      if (type !== 'blob') throw new Error('Submodules are not standalone source files: ' + path);
      assertExportEntry(path, mode);
      return path;
    });
  for (const path of ['packages/node/package.json', 'packages/node/package-lock.json', '.github/workflows/colp-ci.yml',
    'scripts/production-source-size.mjs', 'scripts/scan-tracked-secrets.mjs', 'scripts/secret-scan-allowlist.json', 'scripts/github-action-pins.json']) {
    if (!entries.includes(path)) throw new Error('Missing required standalone tool: ' + path);
  }
  await mkdir(dirname(destination), { recursive: true });
  const staging = await mkdtemp(resolve(dirname(destination), '.colp-export-'));
  const archive = resolve(staging, 'source.tar');
  const content = resolve(staging, 'source');
  try {
    await mkdir(content);
    await git(['archive', '--format=tar', '--output=' + archive, sourceRevision, '--', ...standaloneRoots]);
    await exec('tar', ['-xf', archive, '-C', content]);
    const allowlistPath = resolve(content, 'scripts/secret-scan-allowlist.json');
    const allowlist = filterStandaloneAllowlist(JSON.parse(await readFile(allowlistPath, 'utf8')));
    await writeFile(allowlistPath, JSON.stringify(allowlist, null, 2) + '\n');
    await assertRelativeModuleClosure(content, entries);
    await writeFile(resolve(content, 'COLP_EXPORT.json'), JSON.stringify({ formatVersion: 1, sourceRevision,
      includesParentHistory: false, fileCount: entries.length, moduleClosure: 'checked',
      layout: { protocol: 'protocol/', package: 'packages/node/', tooling: 'scripts/' },
      historyAuditArchive: 'docs/history/r02-parent-history-contract.test.ts.txt',
      releaseEvidence: 'must regenerate against the new repository history',
      runtimeAcceptance: 'not run by exporter' }, null, 2) + '\n');
    if ((await git(['rev-parse', 'HEAD'])).trim() !== sourceRevision) throw new Error('Source HEAD changed during export.');
    await rename(content, destination);
    return { destination, sourceRevision, fileCount: entries.length };
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 3) throw new Error('Usage: node packages/node/scripts/export-standalone.mjs /new/outside/directory');
  console.log(JSON.stringify(await exportStandalone(process.argv[2]), null, 2));
}
