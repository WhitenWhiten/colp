import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const limits = JSON.parse(await readFile(new URL('protocol/replica-health-limits.json', root), 'utf8'));
const source = '// Generated by scripts/generate-replica-health-limits.mjs; edit protocol/replica-health-limits.json.\n'
  + Object.entries(limits).map(([key, value]) => `export const ${key} = ${value};\n`).join('');
for (const path of ['packages/extension/src/generated/replica-health-limits.ts',
  'packages/server/src/modules/sync/generated/replica-health-limits.ts']) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== source) throw new Error(`Replica health limit drift: ${path}`);
  } else await writeFile(url, source);
}
