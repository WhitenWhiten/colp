import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const schemas = await Promise.all(['collection-protocol.schema.json', 'collection-protocol-0.2.schema.json']
  .map(async name => JSON.parse(await readFile(new URL(`protocol/schemas/${name}`, root), 'utf8'))));
const definitions = {};
function include(name, schema = schemas[1]) {
  if (Object.hasOwn(definitions, name)) return;
  const definition = structuredClone(schema.$defs[name]);
  if (!definition) throw new Error(`Missing resilience schema definition: ${name}`);
  definitions[name] = definition;
  function visit(value) {
    if (!value || typeof value !== 'object') return;
    if (typeof value.$ref === 'string') {
      const [base, target] = value.$ref.split('#/$defs/');
      const owner = base ? schemas.find(candidate => candidate.$id === base) : schema;
      if (!owner || !target) throw new Error(`Unknown resilience schema reference: ${value.$ref}`);
      include(target, owner);
      value.$ref = `#/$defs/${target}`;
    }
    for (const child of Object.values(value)) visit(child);
  }
  visit(definition);
}
for (const name of ['syncReplicaHealthReport', 'syncReplicaHealthResult', 'syncReplicaCommand']) include(name);
const source = '// Generated by scripts/generate-sync-resilience-schema.mjs from the protocol schemas.\n'
  + `export default ${JSON.stringify({ $schema: schemas[1].$schema, $defs: definitions }, null, 2)};\n`;
const target = new URL('packages/conformance/src/generated/sync-resilience-schema.mjs', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Sync resilience schema drift');
} else {
  await mkdir(new URL('.', target), { recursive: true });
  await writeFile(target, source);
}
